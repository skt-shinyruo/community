  env_line DB_USERNAME "$(resolve_process_env_then_dotenv_then_fallback MYSQL_USER community)"
  env_line DB_PASSWORD "$(require_process_env_then_dotenv_value MYSQL_PASSWORD)"
  env_line SPRING_DATA_REDIS_HOST 127.0.0.1
  env_line SPRING_DATA_REDIS_PORT "$(require_process_env_then_dotenv_value REDIS_HOST_PORT)"
  env_line KAFKA_BOOTSTRAP_SERVERS "127.0.0.1:$(require_process_env_then_dotenv_value KAFKA_HOST_PORT)"
  env_line ELASTICSEARCH_URIS "http://127.0.0.1:$(require_process_env_then_dotenv_value ELASTICSEARCH_HOST_ACCESS_PORT)"
  env_line SPRING_MAIL_HOST 127.0.0.1
  env_line SPRING_MAIL_PORT "$(require_process_env_then_dotenv_value MAILHOG_SMTP_HOST_PORT)"
