#!/usr/bin/env bash
set -euo pipefail
umask 077

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
  echo "usage: $0 <infra-env-file> [output-dir]" >&2
  exit 1
fi

ENV_FILE="$1"
output_dir="${2:-backend/env/generated}"

if [ ! -f "${ENV_FILE}" ]; then
  echo "[render-backend-env] env file not found: ${ENV_FILE}" >&2
  exit 1
fi

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
. "${SCRIPT_DIR}/lib/dotenv.sh"

require_process_env_then_dotenv_value() {
  local variable="$1"
  local resolved
  resolved="$(resolve_process_env_then_dotenv_then_fallback "${variable}")"
  if [ -z "${resolved}" ]; then
    echo "[render-backend-env] ${variable} is required" >&2
    exit 1
  fi
  printf '%s' "${resolved}"
}

quote_env_value() {
  local quoted="$1"
  quoted="${quoted//\\/\\\\}"
  quoted="${quoted//\"/\\\"}"
  quoted="${quoted//\$/\\\$}"
  quoted="${quoted//\`/\\\`}"
  printf '"%s"' "${quoted}"
}

env_line() {
  local variable="$1"
  local resolved="$2"
  printf '%s=%s\n' "${variable}" "$(quote_env_value "${resolved}")"
}

write_common() {
  local server_port="$1"
  cat <<'EOF'
# Generated by ./deploy/deployment.sh render-backend-env --stack infra. Do not edit.
EOF
  env_line SERVER_PORT "${server_port}"
  env_line SPRING_PROFILES_ACTIVE "$(resolve_process_env_then_dotenv_then_fallback SPRING_PROFILES_ACTIVE dev)"
  env_line DEPLOYMENT_ENVIRONMENT "$(resolve_process_env_then_dotenv_then_fallback DEPLOYMENT_ENVIRONMENT development)"
  env_line SERVICE_VERSION local-infra
  env_line OTEL_ENABLED false
  env_line NACOS_SERVER_ADDR "127.0.0.1:$(require_process_env_then_dotenv_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_DISCOVERY_SERVER_ADDR "127.0.0.1:$(require_process_env_then_dotenv_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_CONFIG_SERVER_ADDR "127.0.0.1:$(require_process_env_then_dotenv_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_DISCOVERY_IP 127.0.0.1
  env_line NACOS_CONFIG_GROUP "$(resolve_process_env_then_dotenv_then_fallback NACOS_CONFIG_GROUP COMMUNITY)"
  env_line NACOS_NAMESPACE "$(resolve_process_env_then_dotenv_then_fallback NACOS_NAMESPACE)"
}

mkdir -p "${output_dir}"

