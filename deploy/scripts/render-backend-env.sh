#!/usr/bin/env bash
set -euo pipefail
umask 077

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
  echo "usage: $0 <infra-env-file> [output-dir]" >&2
  exit 1
fi

env_file="$1"
output_dir="${2:-backend/env/generated}"

if [ ! -f "${env_file}" ]; then
  echo "[render-backend-env] env file not found: ${env_file}" >&2
  exit 1
fi

read_env_value() {
  local variable="$1"
  awk -v variable="${variable}" '
    /^[[:space:]]*(#|$)/ { next }
    {
      line = $0
      sub(/\r$/, "", line)
      prefix = "^[[:space:]]*(export[[:space:]]+)?" variable "[[:space:]]*="
      if (line ~ prefix) {
        sub(prefix, "", line)
        sub(/^[[:space:]]+/, "", line)
        sub(/[[:space:]]+$/, "", line)
        if (length(line) >= 2) {
          first = substr(line, 1, 1)
          last = substr(line, length(line), 1)
          if ((first == "\"" && last == "\"") || (first == "\047" && last == "\047")) {
            line = substr(line, 2, length(line) - 2)
          }
        }
        value = line
        found = 1
      }
    }
    END {
      if (!found) exit 1
      print value
    }
  ' "${env_file}"
}

value() {
  local variable="$1"
  local fallback="${2:-}"
  local resolved

  if [[ -v "${variable}" ]]; then
    resolved="${!variable}"
  elif resolved="$(read_env_value "${variable}")"; then
    :
  else
    resolved="${fallback}"
  fi
  printf '%s' "${resolved}"
}

required_value() {
  local variable="$1"
  local resolved
  resolved="$(value "${variable}")"
  if [ -z "${resolved}" ]; then
    echo "[render-backend-env] ${variable} is required" >&2
    exit 1
  fi
  printf '%s' "${resolved}"
}

quote_env_value() {
  local quoted="$1"
  quoted="${quoted//\\/\\\\}"
  quoted="${quoted//\"/\\\"}"
  quoted="${quoted//\$/\\\$}"
  quoted="${quoted//\`/\\\`}"
  printf '"%s"' "${quoted}"
}

env_line() {
  local variable="$1"
  local resolved="$2"
  printf '%s=%s\n' "${variable}" "$(quote_env_value "${resolved}")"
}

write_common() {
  local server_port="$1"
  cat <<'EOF'
# Generated by ./deploy/deployment.sh render-backend-env --stack infra. Do not edit.
EOF
  env_line SERVER_PORT "${server_port}"
  env_line SPRING_PROFILES_ACTIVE "$(value SPRING_PROFILES_ACTIVE dev)"
  env_line DEPLOYMENT_ENVIRONMENT "$(value DEPLOYMENT_ENVIRONMENT development)"
  env_line SERVICE_VERSION local-infra
  env_line OTEL_ENABLED false
  env_line NACOS_SERVER_ADDR "127.0.0.1:$(required_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_DISCOVERY_SERVER_ADDR "127.0.0.1:$(required_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_CONFIG_SERVER_ADDR "127.0.0.1:$(required_value NACOS_HOST_PORT)"
  env_line SPRING_CLOUD_NACOS_DISCOVERY_IP 127.0.0.1
  env_line NACOS_CONFIG_GROUP "$(value NACOS_CONFIG_GROUP COMMUNITY)"
  env_line NACOS_NAMESPACE "$(value NACOS_NAMESPACE)"
}

mkdir -p "${output_dir}"

