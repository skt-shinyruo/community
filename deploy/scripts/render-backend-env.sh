  env_line METRICS_BASIC_AUTH_USERNAME "$(value METRICS_BASIC_AUTH_USERNAME prometheus)"
  env_line METRICS_BASIC_AUTH_PASSWORD "$(required_value METRICS_BASIC_AUTH_PASSWORD)"
  env_line DB_URL "jdbc:mysql://127.0.0.1:$(required_value MYSQL_HOST_PORT)/community?useUnicode=true&characterEncoding=utf8&serverTimezone=UTC&useSSL=false&allowPublicKeyRetrieval=true"
  env_line DB_USERNAME "$(value MYSQL_USER community)"
